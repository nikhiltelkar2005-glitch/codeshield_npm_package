import * as fs from 'node:fs';
import * as path from 'node:path';
import * as readline from 'node:readline';

import { isEnvIgnoredByGitignore } from '../scanners/env.js';
import { sanitize } from '../utils/sanitize.js';

export interface PlannedFix {
  id: string;
  title: string;
  filePath: string;
  relativePath: string;
  isCreation: boolean;
  backupPath?: string;
  diffLines: string[];
  apply: () => void;
}

export function resolveSafePath(root: string, relativePath: string): string {
  const resolvedRoot = path.resolve(root);
  const resolvedTarget = path.resolve(resolvedRoot, relativePath);

  if (resolvedTarget !== resolvedRoot && !resolvedTarget.startsWith(resolvedRoot + path.sep)) {
    throw new Error(
      `Path traversal attempt rejected: "${sanitize(relativePath)}" is outside the scan root "${sanitize(root)}"`,
    );
  }

  return resolvedTarget;
}

export function generateEnvExampleContent(envContent: string): string {
  const lines = envContent.split('\n');
  const result: string[] = [
    '# .env.example — generated by CodeShield',
    '# Replace with your actual credentials in .env (never commit .env)',
    '',
  ];

  const SENSITIVE_KEY_RE = /(?:key|secret|token|password|passwd|pwd|auth|credential|salt|nonce|hash|private|jwt|database_url|db_url)/i;

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.length === 0 || trimmed.startsWith('#')) {
      result.push(line);
      continue;
    }

    const eqIdx = line.indexOf('=');
    if (eqIdx === -1) {
      result.push(line);
      continue;
    }

    const key = line.slice(0, eqIdx).trim();
    const rawVal = line.slice(eqIdx + 1).trim();

    if (SENSITIVE_KEY_RE.test(key) || rawVal.length > 20) {
      const placeholder = `your_${key.toLowerCase()}_here`;
      result.push(`${key}=${placeholder}`);
    } else {
      result.push(line);
    }
  }

  return result.join('\n') + '\n';
}

export function planFixes(root: string): PlannedFix[] {
  const safeRoot = path.resolve(root);
  const fixes: PlannedFix[] = [];

  const envPath = resolveSafePath(safeRoot, '.env');
  const envExists = fs.existsSync(envPath);

  const gitignorePath = resolveSafePath(safeRoot, '.gitignore');
  const gitignoreExists = fs.existsSync(gitignorePath);

  let gitignoreNeedsEnv = false;
  let gitignoreNeedsCodeshield = false;

  if (gitignoreExists) {
    const gitignoreContent = fs.readFileSync(gitignorePath, 'utf8');
    gitignoreNeedsEnv = envExists && !isEnvIgnoredByGitignore('.env', gitignoreContent);
    gitignoreNeedsCodeshield = !gitignoreContent.includes('.codeshield');
  } else if (envExists) {
    gitignoreNeedsEnv = true;
    gitignoreNeedsCodeshield = true;
  }

  if (gitignoreNeedsEnv || gitignoreNeedsCodeshield) {
    const linesToAdd: string[] = [];
    if (gitignoreNeedsEnv) {
      linesToAdd.push(
        '# CodeShield: Ignore local environment credentials',
        '.env',
        '.env.local',
        '.env.*.local',
      );
    }
    if (gitignoreNeedsCodeshield) {
      linesToAdd.push(
        '# CodeShield: Ignore local scan history cache',
        '.codeshield/',
      );
    }

    const diffLines = linesToAdd.map(l => `+ ${l}`);
    const backupPath = gitignoreExists ? `${gitignorePath}.codeshield.bak` : undefined;

    fixes.push({
      id: 'FIX-GITIGNORE',
      title: gitignoreExists
        ? 'Add .env and .codeshield/ to .gitignore'
        : 'Create .gitignore with .env and .codeshield/',
      filePath: gitignorePath,
      relativePath: '.gitignore',
      isCreation: !gitignoreExists,
      ...(backupPath ? { backupPath } : {}),
      diffLines,
      apply: () => {
        if (gitignoreExists) {
          fs.copyFileSync(gitignorePath, backupPath!);
          const current = fs.readFileSync(gitignorePath, 'utf8');
          const prefix = current.endsWith('\n') || current.length === 0 ? '' : '\n';
          fs.appendFileSync(gitignorePath, prefix + linesToAdd.join('\n') + '\n', 'utf8');
        } else {
          fs.writeFileSync(gitignorePath, linesToAdd.join('\n') + '\n', 'utf8');
        }
      },
    });
  }

  const envExamplePath = resolveSafePath(safeRoot, '.env.example');
  const envExampleExists = fs.existsSync(envExamplePath);

  if (envExists && !envExampleExists) {
    const envContent = fs.readFileSync(envPath, 'utf8');
    const exampleContent = generateEnvExampleContent(envContent);
    const diffLines = exampleContent.trim().split('\n').map(l => `+ ${l}`);

    fixes.push({
      id: 'FIX-ENV-EXAMPLE',
      title: 'Create .env.example template from .env',
      filePath: envExamplePath,
      relativePath: '.env.example',
      isCreation: true,
      diffLines,
      apply: () => {
        fs.writeFileSync(envExamplePath, exampleContent, 'utf8');
      },
    });
  }

  return fixes;
}

export function formatFixDiff(fixes: PlannedFix[]): string {
  const lines: string[] = [
    '\nCodeShield Fix Plan:',
    '────────────────────────────────────────────────────────────',
  ];

  for (let i = 0; i < fixes.length; i++) {
    const fix = fixes[i]!;
    lines.push(`[${i + 1}] ${fix.title}`);
    lines.push(`    Target : ${fix.relativePath}`);
    if (fix.backupPath) {
      lines.push(`    Backup : ${path.basename(fix.backupPath)}`);
    }
    lines.push('    Changes:');
    for (const d of fix.diffLines) {
      lines.push(`      ${d}`);
    }
    lines.push('');
  }

  lines.push('────────────────────────────────────────────────────────────');
  return lines.join('\n');
}

export async function promptConfirmation(question: string): Promise<boolean> {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  return new Promise((resolve) => {
    rl.question(question, (answer) => {
      rl.close();
      const trimmed = answer.trim().toLowerCase();
      resolve(trimmed === 'y' || trimmed === 'yes');
    });
  });
}

export async function runFix(root: string, autoConfirm = false): Promise<number> {
  const safeRoot = path.resolve(root);

  let fixes: PlannedFix[];
  try {
    fixes = planFixes(safeRoot);
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error(`Error planning fixes: ${sanitize(msg)}`);
    return 2;
  }

  if (fixes.length === 0) {
    console.log('\n✅ No automatic fixes needed. Codebase looks clean!');
    return 0;
  }

  console.log(formatFixDiff(fixes));

  if (!autoConfirm) {
    const confirmed = await promptConfirmation('Apply these changes? [y/N]: ');
    if (!confirmed) {
      console.log('\nOperation cancelled. No files were modified.');
      return 0;
    }
  }

  try {
    for (const fix of fixes) {
      fix.apply();
      console.log(`✅ Applied: ${fix.title}`);
      if (fix.backupPath) {
        console.log(`   (Backup created at ${path.basename(fix.backupPath)})`);
      }
    }
    console.log(`\n🎉 Successfully applied ${fixes.length} fix${fixes.length === 1 ? '' : 'es'}.\n`);
    return 0;
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error(`Error applying fixes: ${sanitize(msg)}`);
    return 2;
  }
}
